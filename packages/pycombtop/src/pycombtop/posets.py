"""Finite posets and the order-complex constructions of LPV08.

The order is stored as reflexive upper and lower sets. Poset operations do
not require enumerating chains. Graph conversions use NetworkX and therefore
cannot use None as a graph vertex (posets themselves can use that label).
"""

from __future__ import annotations

from collections.abc import Hashable, Iterable, Iterator, Mapping
from dataclasses import dataclass
from itertools import combinations, combinations_with_replacement, product
from typing import Literal

import networkx as nx

from .simplex import Simplex, SimplicialComplex, all_subsets, clique_complex


class Poset:
    """Finite partial order on arbitrary hashable labels.

    Supply elements and strict generating pairs (lower, upper), normally
    Hasse edges. Redundant edges are accepted; cycles and unknown endpoints
    are rejected. Isolated elements must be supplied explicitly.
    """

    def __init__(
        self,
        elements: Iterable[Hashable],
        covers: Iterable[tuple[Hashable, Hashable]] = (),
    ) -> None:
        self._elements = tuple(dict.fromkeys(elements))
        index = {x: i for i, x in enumerate(self._elements)}
        dag = nx.DiGraph()
        dag.add_nodes_from(range(len(index)))
        for a, b in covers:
            if a not in index or b not in index:
                raise ValueError("relation endpoint outside the poset")
            dag.add_edge(index[a], index[b])
        if not nx.is_directed_acyclic_graph(dag):
            raise ValueError("strict generating relation must be acyclic")
        upper: dict[Hashable, set[Hashable]] = {}
        for i in reversed(list(nx.topological_sort(dag))):
            x = self._elements[i]
            upper[x] = {x}
            for j in dag.successors(i):
                upper[x].update(upper[self._elements[j]])
        lower: dict[Hashable, set[Hashable]] = {x: set() for x in self}
        for x, successors in upper.items():
            for y in successors:
                lower[y].add(x)
        self._upper = {x: frozenset(s) for x, s in upper.items()}
        self._lower = {x: frozenset(s) for x, s in lower.items()}

    @classmethod
    def from_covers(
        cls,
        elements: Iterable[Hashable],
        covers: Iterable[tuple[Hashable, Hashable]],
    ) -> Poset:
        """Build the order generated by strict covering pairs."""
        return cls(elements, covers)

    @classmethod
    def from_relation(
        cls,
        elements: Iterable[Hashable],
        relation: Iterable[tuple[Hashable, Hashable]],
    ) -> Poset:
        """Build from a transitive relation, with optional diagonal pairs."""
        labels = tuple(dict.fromkeys(elements))
        pairs = set(relation)
        if any(a not in labels or b not in labels for a, b in pairs):
            raise ValueError("relation endpoint outside the poset")
        strict = {(a, b) for a, b in pairs if a != b}
        result = cls(labels, strict)
        if set(result.relation(strict=True)) != strict:
            raise ValueError("order relation is not transitive")
        return result

    @classmethod
    def from_order_matrix(
        cls, elements: Iterable[Hashable], matrix: Iterable[Iterable[bool]]
    ) -> Poset:
        """Build from a reflexive Boolean matrix, row <= column."""
        labels = tuple(elements)
        rows = tuple(tuple(row) for row in matrix)
        n = len(labels)
        if (
            len(set(labels)) != n
            or len(rows) != n
            or any(len(row) != n for row in rows)
        ):
            raise ValueError("matrix must be square with distinct labels")
        if any(v not in (0, 1) for row in rows for v in row):
            raise ValueError("matrix entries must be Boolean")
        if any(not rows[i][i] for i in range(n)):
            raise ValueError("matrix must be reflexive")
        return cls.from_relation(
            labels,
            (
                (a, b)
                for i, a in enumerate(labels)
                for j, b in enumerate(labels)
                if rows[i][j]
            ),
        )

    @property
    def elements(self) -> tuple[Hashable, ...]:
        """Elements in input order."""
        return self._elements

    def __iter__(self) -> Iterator[Hashable]:
        return iter(self._elements)

    def __len__(self) -> int:
        return len(self._elements)

    def __contains__(self, x: object) -> bool:
        return x in self._upper

    def __eq__(self, other: object) -> bool:
        return isinstance(other, Poset) and self._upper == other._upper

    def leq(self, a: Hashable, b: Hashable) -> bool:
        """Whether a <= b; unknown labels raise KeyError."""
        if b not in self:
            raise KeyError(b)
        return b in self._upper[a]

    def comparable(self, a: Hashable, b: Hashable) -> bool:
        """Whether the two elements are comparable."""
        return self.leq(a, b) or self.leq(b, a)

    def upper_set(self, x: Hashable, *, strict: bool = False) -> frozenset[Hashable]:
        """Principal upper set, optionally excluding x."""
        return self._upper[x] - {x} if strict else self._upper[x]

    def lower_set(self, x: Hashable, *, strict: bool = False) -> frozenset[Hashable]:
        """Principal lower set, optionally excluding x."""
        return self._lower[x] - {x} if strict else self._lower[x]

    def relation(self, *, strict: bool = False) -> Iterator[tuple[Hashable, Hashable]]:
        """Iterate over ordered pairs."""
        for a in self:
            for b in self.upper_set(a, strict=strict):
                yield a, b

    def upper_covers(self, x: Hashable) -> frozenset[Hashable]:
        """Immediate strict successors."""
        upper = self.upper_set(x, strict=True)
        return frozenset(
            y for y in upper if not (upper & self.lower_set(y, strict=True))
        )

    def lower_covers(self, x: Hashable) -> frozenset[Hashable]:
        """Immediate strict predecessors."""
        lower = self.lower_set(x, strict=True)
        return frozenset(
            y for y in lower if not (lower & self.upper_set(y, strict=True))
        )

    def minimal_elements(self) -> frozenset[Hashable]:
        """Minimal elements."""
        return frozenset(x for x in self if len(self._lower[x]) == 1)

    def maximal_elements(self) -> frozenset[Hashable]:
        """Maximal elements."""
        return frozenset(x for x in self if len(self._upper[x]) == 1)

    def induced(self, elements: Iterable[Hashable]) -> Poset:
        """Restrict the order, not just the original Hasse edges."""
        keep = frozenset(elements)
        if not keep <= self._upper.keys():
            raise ValueError("induced elements outside the poset")
        return Poset(
            (x for x in self if x in keep),
            (
                (a, b)
                for a in self
                if a in keep
                for b in self.upper_set(a, strict=True) & keep
            ),
        )

    def dual(self) -> Poset:
        """Reverse the order."""
        return Poset(self, ((b, a) for a, b in self.relation(strict=True)))

    def interval(self, a: Hashable, b: Hashable) -> frozenset[Hashable]:
        """Closed interval [a,b], empty if a is not below b."""
        return self.upper_set(a) & self.lower_set(b)

    def upper_bounds(self, elements: Iterable[Hashable]) -> frozenset[Hashable]:
        """Common upper bounds (all elements for the empty family)."""
        result = frozenset(self)
        for x in elements:
            result &= self.upper_set(x)
        return result

    def lower_bounds(self, elements: Iterable[Hashable]) -> frozenset[Hashable]:
        """Common lower bounds (all elements for the empty family)."""
        result = frozenset(self)
        for x in elements:
            result &= self.lower_set(x)
        return result

    def join(self, elements: Iterable[Hashable]) -> Hashable:
        """Least upper bound; raise ValueError if none exists."""
        bounds = self.upper_bounds(elements)
        for x in bounds:
            if bounds <= self.upper_set(x):
                return x
        raise ValueError("no least upper bound")

    def meet(self, elements: Iterable[Hashable]) -> Hashable:
        """Greatest lower bound; raise ValueError if none exists."""
        bounds = self.lower_bounds(elements)
        for x in bounds:
            if bounds <= self.lower_set(x):
                return x
        raise ValueError("no greatest lower bound")

    def comparability_graph(self) -> nx.Graph:
        """Graph on elements, with edges between distinct comparable points."""
        graph = nx.Graph()
        graph.add_nodes_from(self)
        graph.add_edges_from(self.relation(strict=True))
        return graph

    def maximal_chains(self) -> Iterator[Simplex]:
        """Enumerate maximal chains only, including isolated singletons."""
        # Integer labels allow arbitrary hashable poset labels, including None.
        indices = {x: i for i, x in enumerate(self)}
        graph = nx.Graph()
        graph.add_nodes_from(range(len(self)))
        graph.add_edges_from(
            (indices[a], indices[b]) for a, b in self.relation(strict=True)
        )
        for chain in nx.find_cliques(graph):
            yield Simplex(self._elements[i] for i in chain)

    def is_order_preserving(
        self, target: Poset, mapping: Mapping[Hashable, Hashable]
    ) -> bool:
        """Test a total map into target for monotonicity."""
        return (
            set(mapping) == set(self)
            and all(y in target for y in mapping.values())
            and all(target.leq(mapping[a], mapping[b]) for a, b in self.relation())
        )

    def is_ideal(self, elements: Iterable[Hashable]) -> bool:
        """Whether the supplied subset is a down-set."""
        subset = frozenset(elements)
        return subset <= self._upper.keys() and all(
            self.lower_set(x) <= subset for x in subset
        )


def order_complex(poset: Poset) -> SimplicialComplex:
    """Order complex, constructed from maximal chains rather than all chains."""
    facets = list(poset.maximal_chains()) if len(poset) else [Simplex([])]
    return SimplicialComplex(poset, facet_set=facets)


def face_poset(complex_: SimplicialComplex) -> Poset:
    """Inclusion order on nonempty faces; excludes ghost vertices."""
    faces = {face for face in complex_.all_simplices() if face}
    return Poset(
        faces,
        (
            (Simplex(face - {x}), face)
            for face in faces
            if len(face) > 1
            for x in face
        ),
    )


def complete_poset(graph: nx.Graph) -> Poset:
    """The poset P(G) of nonempty complete subgraphs, ordered by inclusion."""
    return face_poset(clique_complex(graph))


def product_poset(first: Poset, second: Poset) -> Poset:
    """Cartesian product with coordinatewise order."""
    elements = tuple(product(first, second))
    edges = [((a, b), (c, b)) for a, b in elements for c in first.upper_covers(a)]
    edges.extend(
        ((a, b), (a, d)) for a, b in elements for d in second.upper_covers(b)
    )
    return Poset(elements, edges)


@dataclass(frozen=True)
class BeatMove:
    """A beat-point deletion with its unique extremal strict neighbor."""

    point: Hashable
    witness: Hashable
    direction: Literal["up", "down"]


@dataclass(frozen=True)
class BeatReduction:
    """A finite-space core and a replayable deletion trace."""

    core: Poset
    moves: tuple[BeatMove, ...]


def beat_moves(poset: Poset) -> Iterator[BeatMove]:
    """Enumerate up/down beat points and their witnesses."""
    for x in poset:
        for direction, covers in (
            ("up", poset.upper_covers(x)),
            ("down", poset.lower_covers(x)),
        ):
            if len(covers) == 1:
                # Spell out literals for static type checking.
                if direction == "up":
                    yield BeatMove(x, next(iter(covers)), "up")
                else:
                    yield BeatMove(x, next(iter(covers)), "down")


def beat_core(poset: Poset) -> BeatReduction:
    """Reduce to a core for finite Alexandrov-space homotopy."""
    current = poset
    moves: list[BeatMove] = []
    while (move := next(beat_moves(current), None)) is not None:
        moves.append(move)
        current = current.induced(x for x in current if x != move.point)
    return BeatReduction(current, tuple(moves))


def verify_beat_reduction(poset: Poset, reduction: BeatReduction) -> bool:
    """Replay each strict-neighbor condition and check the endpoint is a core."""
    if not isinstance(reduction, BeatReduction):
        return False
    current = poset
    for move in reduction.moves:
        if not isinstance(move, BeatMove) or move not in beat_moves(current):
            return False
        current = current.induced(x for x in current if x != move.point)
    return current == reduction.core and next(beat_moves(current), None) is None


def omega(poset: Poset) -> nx.Graph:
    """LPV08 Omega: minimal elements with a common upper bound."""
    graph = nx.Graph()
    minima = poset.minimal_elements()
    graph.add_nodes_from(minima)
    for top in poset.maximal_elements():
        graph.add_edges_from(combinations(poset.lower_set(top) & minima, 2))
    return graph


def mho(poset: Poset) -> nx.Graph:
    """LPV08 Mho: maximal elements with a common lower bound."""
    return omega(poset.dual())


def bounded_complex(poset: Poset, *, upper: bool = True) -> SimplicialComplex:
    """Bounded subsets of minima (upper) or maxima (lower), LPV08 section 5."""
    if not upper:
        return bounded_complex(poset.dual())
    minima = poset.minimal_elements()
    facets = [minima & poset.lower_set(x) for x in poset.maximal_elements()]
    return SimplicialComplex(minima, facet_set=facets or [Simplex([])])


def bounded_complete_poset(poset: Poset, *, upper: bool = True) -> Poset:
    """P_b Omega or P_b Mho, the face poset of the bounded complex."""
    return face_poset(bounded_complex(poset, upper=upper))


def is_down_helly(poset: Poset) -> bool:
    """Every nonempty complete of Omega has a common upper bound."""
    minima = tuple(poset.minimal_elements())
    graph = nx.Graph()
    graph.add_nodes_from(range(len(minima)))
    graph.add_edges_from(
        (i, j)
        for i, j in combinations(range(len(minima)), 2)
        if poset.upper_bounds((minima[i], minima[j]))
    )
    return all(
        poset.upper_bounds(minima[i] for i in c) for c in nx.find_cliques(graph)
    )


def is_up_helly(poset: Poset) -> bool:
    """Every nonempty complete of Mho has a common lower bound."""
    return is_down_helly(poset.dual())


def is_up_sperner(poset: Poset) -> bool:
    """Distinct maximal points have incomparable sets of minimal predecessors."""
    minima = poset.minimal_elements()
    stars = [minima & poset.lower_set(x) for x in poset.maximal_elements()]
    return not any(a <= b or b <= a for a, b in combinations(stars, 2))


def is_down_sperner(poset: Poset) -> bool:
    """Dual of up-Sperner."""
    return is_up_sperner(poset.dual())


def is_atomized(poset: Poset) -> bool:
    """Every nonempty bounded subset of minima has a join.

    It suffices to test the common minimal predecessors of pairs of points,
    including equal pairs. This makes the upper bounds of each bounded
    subset downward directed and hence gives a least upper bound.
    """
    minima = poset.minimal_elements()
    for a, b in combinations_with_replacement(poset, 2):
        common = minima & poset.lower_set(a) & poset.lower_set(b)
        if common:
            try:
                poset.join(common)
            except ValueError:
                return False
    return True


def is_coatomized(poset: Poset) -> bool:
    """Dual of atomized, using meets of nonempty sets of maxima."""
    return is_atomized(poset.dual())


def atomic_projection(poset: Poset) -> dict[Hashable, Hashable]:
    """Map each point to the join of its minimal predecessors."""
    if not is_atomized(poset):
        raise ValueError("poset must be atomized")
    minima = poset.minimal_elements()
    return {x: poset.join(minima & poset.lower_set(x)) for x in poset}


def coatomic_projection(poset: Poset) -> dict[Hashable, Hashable]:
    """LPV08 h: meet of the maximal successors of each point."""
    return atomic_projection(poset.dual())


def atomic_subposet(poset: Poset) -> Poset:
    """Image of the descending atomic projection."""
    return poset.induced(atomic_projection(poset).values())


def coatomic_subposet(poset: Poset) -> Poset:
    """Image of h, the ascending coatomic projection."""
    return poset.induced(coatomic_projection(poset).values())


def is_strongly_up_sperner(poset: Poset) -> bool:
    """Atomized with every point equal to its atomic projection."""
    if not is_atomized(poset):
        return False
    return all(x == y for x, y in atomic_projection(poset).items())


def is_join_increasing(poset: Poset) -> bool:
    """Strict inclusion of nonempty bounded minimal sets implies strict joins."""
    if not is_atomized(poset):
        return False
    minima = poset.minimal_elements()
    for x in poset:
        atoms = minima & poset.lower_set(x)
        if len(atoms) > 1:
            # A violation can be enlarged to all atoms below the common join
            # except for one atom not belonging to the smaller set.
            if any(poset.join(atoms - {a}) == x for a in atoms):
                return False
    return True


def interval_poset(poset: Poset) -> Poset:
    """Nonempty closed intervals, labeled by endpoint pairs, ordered by inclusion."""
    intervals = tuple(poset.relation())
    edges = [((a, b), (c, b)) for a, b in intervals for c in poset.lower_covers(a)]
    edges.extend(
        ((a, b), (a, d)) for a, b in intervals for d in poset.upper_covers(b)
    )
    return Poset(intervals, edges)


def double_bound_graph(poset: Poset) -> nx.Graph:
    """General DB(P); labels are points, not singleton intervals.

    For graphs use pycliques.double_bound_graph, which avoids building P(G).
    """
    graph = nx.Graph()
    graph.add_nodes_from(poset)
    graph.add_edges_from(
        (a, b)
        for a, b in combinations(poset, 2)
        if poset.upper_bounds((a, b)) and poset.lower_bounds((a, b))
    )
    return graph


def nice_fibers(ambient: Poset, subposet: Poset) -> dict[Hashable, Poset]:
    """Fibers Q <= h(x) in the LPV08 definition of a nice subposet.

    This only constructs the fibers; their contractibility must be proved
    separately, e.g. by applying the existing homotopy tools to their order
    complexes. A failed proof is not a proof that Q is not nice.
    """
    if not set(subposet) <= set(ambient) or ambient.induced(subposet) != subposet:
        raise ValueError("expected an induced subposet")
    return {
        x: subposet.induced(set(subposet) & ambient.lower_set(y))
        for x, y in coatomic_projection(ambient).items()
    }


def crosscut_complex(poset: Poset, elements: Iterable[Hashable]) -> SimplicialComplex:
    """Complex of subsets bounded above or below, on a supplied subset."""
    subset = frozenset(elements)
    if not subset <= set(poset):
        raise ValueError("crosscut elements outside the poset")
    facets = [subset & poset.lower_set(x) for x in poset.maximal_elements()]
    facets.extend(subset & poset.upper_set(x) for x in poset.minimal_elements())
    return SimplicialComplex(subset, facet_set=facets or [Simplex([])])


def is_crosscut(poset: Poset, elements: Iterable[Hashable]) -> bool:
    """Check the crosscut axioms, enumerating bounded nonempty subsets."""
    subset = frozenset(elements)
    if not subset <= set(poset):
        return False
    if any(poset.comparable(a, b) for a, b in combinations(subset, 2)):
        return False
    if any(not chain & subset for chain in poset.maximal_chains()):
        return False
    for facet in crosscut_complex(poset, subset).facet_set:
        for face in all_subsets(set(facet)):
            try:
                poset.join(face)
            except ValueError:
                try:
                    poset.meet(face)
                except ValueError:
                    return False
    return True


def join_contraction(poset: Poset, point: Hashable) -> dict[Hashable, Hashable]:
    """Conical contraction x -> join(x, point); raise if a join is absent."""
    if point not in poset:
        raise ValueError("contraction point outside the poset")
    return {x: poset.join((x, point)) for x in poset}


def verify_conical_contraction(
    poset: Poset, point: Hashable, mapping: Mapping[Hashable, Hashable]
) -> bool:
    """Verify an order-preserving map with x <= f(x) >= point."""
    return (
        point in poset
        and poset.is_order_preserving(poset, mapping)
        and all(poset.leq(x, y) and poset.leq(point, y) for x, y in mapping.items())
    )


def lower_fibers(
    source: Poset, target: Poset, mapping: Mapping[Hashable, Hashable]
) -> dict[Hashable, Poset]:
    """Inverse images of principal lower sets, for Quillen's fiber theorem.

    This constructs the fibers only, without claiming contractibility.
    """
    if not source.is_order_preserving(target, mapping):
        raise ValueError("expected a total order-preserving map")
    return {
        y: source.induced(x for x in source if target.leq(mapping[x], y))
        for y in target
    }
