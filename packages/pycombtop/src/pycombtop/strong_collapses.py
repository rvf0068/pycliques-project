"""Strong collapses of simplicial complexes over intervals of facet families.

A fixed family M and a possible family E, with M contained in E, specify
all simplicial complexes generated by intermediate families B. A single
certificate can collapse every such complex to the same apex. Facet
candidates need not be inclusion-maximal, particularly after deletions.
"""

from collections.abc import Hashable, Iterable
from dataclasses import dataclass

Family = frozenset[frozenset[Hashable]]
Move = tuple[Hashable, Hashable]


@dataclass(frozen=True)
class UniformStrongCollapseCertificate:
    """Dominated-vertex deletions followed by a common cone with given apex."""

    moves: tuple[Move, ...]
    apex: Hashable


@dataclass(frozen=True)
class UniformStrongCollapseReduction:
    """Uniform collapse prefix and optional certificate of a cone endpoint."""

    moves: tuple[Move, ...]
    certificate: UniformStrongCollapseCertificate | None


def _normalize(
    fixed: Iterable[Iterable[Hashable]],
    possible: Iterable[Iterable[Hashable]],
) -> tuple[Family, Family]:
    m = frozenset(frozenset(f) for f in fixed)
    e = frozenset(frozenset(f) for f in possible)
    if not m or not m <= e or any(not f for f in e):
        raise ValueError("expected nonempty fixed family within nonempty facets")
    return m, e


def _project(family: Family, removed: set[Hashable]) -> Family:
    return frozenset(f - removed for f in family)


def _effective(fixed: Family, possible: Family) -> Family:
    maximal = frozenset(f for f in fixed if not any(f < g for g in fixed))
    optional = frozenset(f for f in possible if not any(f <= g for g in maximal))
    return (maximal | optional) - {frozenset()}


def uniform_strong_collapse_reduction(
    fixed: Iterable[Iterable[Hashable]],
    possible: Iterable[Iterable[Hashable]],
) -> UniformStrongCollapseReduction:
    """Find a uniform strong-collapse prefix on an interval.

    Discard possible faces contained in a mandatory face, retaining maximal
    mandatory faces. In the resulting effective family, inclusion of the
    incidence pattern of v in that of w permits deletion of v uniformly.
    Repeat after restricting to the surviving vertices. A common vertex of
    the effective family is a uniform cone apex. If no cone is found, retain
    the prefix; its moves still preserve every intermediate homotopy type.

    Inputs are nonempty families of nonempty sets, with fixed contained in
    possible as families. Duplicate sets are immaterial. The ordinary
    strong-collapse API in pycliques.poset_homotopy is unchanged.
    """
    m, e = _normalize(fixed, possible)
    moves: list[Move] = []
    while True:
        effective = _effective(m, e)
        incidence: dict[Hashable, int] = {}
        for i, facet in enumerate(effective):
            for v in facet:
                incidence[v] = incidence.get(v, 0) | (1 << i)
        full = (1 << len(effective)) - 1

        def priority(v: Hashable) -> tuple[int, str]:
            return -incidence[v].bit_count(), repr(v)

        order = sorted(incidence, key=priority)
        retained: list[Hashable] = []
        removed: set[Hashable] = set()
        for v in order:
            pattern = incidence[v]
            if pattern == full:
                cert = UniformStrongCollapseCertificate(tuple(moves), v)
                return UniformStrongCollapseReduction(tuple(moves), cert)
            for w in retained:
                if pattern & incidence[w] == pattern:
                    moves.append((v, w))
                    removed.add(v)
                    break
            else:
                retained.append(v)
        if not removed:
            return UniformStrongCollapseReduction(tuple(moves), None)
        m = _project(m, removed)
        e = _project(e, removed)


def uniform_strong_collapse_certificate(
    fixed: Iterable[Iterable[Hashable]],
    possible: Iterable[Iterable[Hashable]],
) -> UniformStrongCollapseCertificate | None:
    """Find a uniform collapse to a cone; None means inconclusive.

    Use uniform_strong_collapse_reduction to retain partial moves on failure.
    """
    return uniform_strong_collapse_reduction(fixed, possible).certificate


def _replay_uniform_prefix(
    m: Family, e: Family, moves: Iterable[Move]
) -> tuple[Family, Family] | None:
    live: set[Hashable] = set().union(*e)
    for move in moves:
        if not isinstance(move, (tuple, list)) or len(move) != 2:
            return None
        v, w = move
        if v == w or v not in live or w not in live:
            return None
        containing = [g for g in m if w in g]
        for f in e:
            if v in f and w not in f and not any(f <= g for g in containing):
                return None
        live.remove(v)
        m = _project(m, {v})
        e = _project(e, {v})
    return m, e


def verify_uniform_strong_collapse_prefix(
    fixed: Iterable[Iterable[Hashable]],
    possible: Iterable[Iterable[Hashable]],
    moves: Iterable[Move],
) -> bool:
    """Replay moves without requiring a cone endpoint.

    The same direct containment check as for a full certificate is used.
    A valid prefix also works on every nested interval, skipping a move
    if its removed vertex is absent. Projecting its fixed and possible
    families onto the surviving vertices permits further certified moves.
    """
    try:
        m, e = _normalize(fixed, possible)
        return _replay_uniform_prefix(m, e, moves) is not None
    except (TypeError, ValueError):
        return False


def verify_uniform_strong_collapse_certificate(
    fixed: Iterable[Iterable[Hashable]],
    possible: Iterable[Iterable[Hashable]],
    certificate: UniformStrongCollapseCertificate,
) -> bool:
    """Independently replay using direct containment in mandatory faces.

    For each deletion (v,w), every possible face containing v but not w
    must be contained in a mandatory face containing w. This guarantees
    that v is dominated whenever present, for every intermediate family.
    The last check uses the same condition for a common cone apex. The
    verifier does not call the incidence-pattern search or its reduction.
    """
    if not isinstance(certificate, UniformStrongCollapseCertificate):
        return False
    try:
        m, e = _normalize(fixed, possible)
        projected = _replay_uniform_prefix(m, e, certificate.moves)
        if projected is None:
            return False
        m, e = projected
        apex = certificate.apex
        containing = [g for g in m if apex in g]
        return bool(containing) and all(
            apex in f or any(f <= g for g in containing) for f in e
        )
    except (TypeError, ValueError):
        return False
